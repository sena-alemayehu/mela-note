import {
  Injectable,
  NotFoundException,
  BadRequestException,
} from '@nestjs/common';

import { NoteStatus } from '../generated/prisma/client';
import { PrismaService } from '../prisma/prisma.service';
import { AttachmentStorageService } from './attachment-storage.service';
import { AuditLogService } from '../audit/audit-log.service';

@Injectable()
export class AttachmentsService {
  constructor(
    private readonly prisma: PrismaService,
    private readonly storage: AttachmentStorageService,
    private readonly auditLog: AuditLogService,
  ) {}

  // Upload an attachment to a user's active note
  async upload(
    userId: string,
    noteId: string,
    file: Express.Multer.File,
    meta?: { ipAddress?: string; userAgent?: string },
  ) {
    if (!file) {
      throw new BadRequestException(
        'Please select a file to upload.',
      );
    }

    // Use the actual filename generated by Multer
    const storageKey = file.filename;

    try {
      // Verify that the note belongs to this user (ownership check)
      const note = await this.prisma.note.findFirst({
        where: {
          id: noteId,
          userId,
          status: NoteStatus.ACTIVE,
        },
        select: {
          id: true,
        },
      });

      if (!note) {
        throw new NotFoundException('Active note not found.');
      }

      const attachment = await this.prisma.attachment.create({
        data: {
          fileName: file.originalname,
          mimeType: file.mimetype,
          sizeBytes: BigInt(file.size),
          storageKey,
          noteId,
        },
      });

      await this.auditLog.logAction({
        userId,
        action: 'ATTACHMENT_UPLOAD',
        details: {
          attachmentId: attachment.id,
          noteId,
          fileName: file.originalname,
          sizeBytes: file.size,
          mimeType: file.mimetype,
        },
        ipAddress: meta?.ipAddress,
        userAgent: meta?.userAgent,
      });

      return {
        id: attachment.id,
        fileName: attachment.fileName,
        mimeType: attachment.mimeType,
        sizeBytes: Number(attachment.sizeBytes),
        createdAt: attachment.createdAt,
        noteId: attachment.noteId,
        downloadUrl: `/api/attachments/${attachment.id}/download`,
      };
    } catch (error) {
      // Clean up the uploaded file if database insert fails
      try {
        await this.storage.deleteFile(storageKey);
      } catch {
        // Preserve the original upload or database error
      }

      throw error;
    }
  }

  // Get all attachments belonging to the signed-in user
  async findAll(userId: string) {
    const attachments = await this.prisma.attachment.findMany({
      where: {
        note: {
          is: {
            userId,
            status: NoteStatus.ACTIVE,
          },
        },
      },
      include: {
        note: {
          select: {
            id: true,
            title: true,
            updatedAt: true,
          },
        },
      },
      orderBy: {
        createdAt: 'desc',
      },
    });

    return attachments.map((attachment) => ({
      id: attachment.id,
      fileName: attachment.fileName,
      mimeType: attachment.mimeType,
      sizeBytes: Number(attachment.sizeBytes),
      createdAt: attachment.createdAt,
      noteId: attachment.noteId,
      noteTitle: attachment.note.title,
      noteUpdatedAt: attachment.note.updatedAt,
      downloadUrl: `/api/attachments/${attachment.id}/download`,
    }));
  }

  // Get a file for download after checking ownership
  async getDownloadFile(
    userId: string,
    attachmentId: string,
  ) {
    const attachment = await this.prisma.attachment.findFirst({
      where: {
        id: attachmentId,
        note: {
          is: {
            userId,
          },
        },
      },
    });

    if (!attachment) {
      throw new NotFoundException('Attachment not found.');
    }

    if (!this.storage.fileExists(attachment.storageKey)) {
      throw new NotFoundException(
        'Attachment file is missing from storage.',
      );
    }

    return {
      path: this.storage.getFilePath(attachment.storageKey),
      fileName: attachment.fileName,
      mimeType: attachment.mimeType,
    };
  }

  // Delete an attachment and its stored file
  async remove(
    userId: string,
    attachmentId: string,
    meta?: { ipAddress?: string; userAgent?: string },
  ) {
    const attachment = await this.prisma.attachment.findFirst({
      where: {
        id: attachmentId,
        note: {
          is: {
            userId,
          },
        },
      },
    });

    if (!attachment) {
      throw new NotFoundException('Attachment not found.');
    }

    // Delete the file first so a failure leaves the database record intact
    await this.storage.deleteFile(attachment.storageKey);

    await this.prisma.attachment.delete({
      where: {
        id: attachmentId,
      },
    });

    await this.auditLog.logAction({
      userId,
      action: 'ATTACHMENT_DELETE',
      details: { attachmentId, fileName: attachment.fileName },
      ipAddress: meta?.ipAddress,
      userAgent: meta?.userAgent,
    });

    return {
      message: 'Attachment deleted successfully.',
    };
  }
}
